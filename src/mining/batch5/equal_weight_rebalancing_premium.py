"""Batch5 candidate: equal_weight_rebalancing_premium (single_long).

Implements the catalogued mechanism from ``data/mining/catalog.json``
under the ABI-1 batch5 module contract. Nothing about the mechanism, the
parameters, or the traded instrument is re-tuned here.

The signal has the simple bare-constant shape (entry=True, exit=False
unconditionally); ``data/mining/catalog.json``'s own "mechanism" field
states the same no-timing-signal design (see below).

Source (pre-registered catalog entry, ``data/mining/catalog.json``,
family_id "equal_weight_rebalancing_premium"): Plyakha, Y., Uppal, R., and
Vilkov, G. (2012), "Why Does an Equal-Weighted Portfolio Outperform Value-
and Price-Weighted Portfolios?" SSRN Working Paper 2724535 (the paper
attributes roughly 42% of equal-weight outperformance directly to the
rebalancing mechanism itself), verified via web search 2026-08-29 per the
catalog entry's own "source" field. Ticker verified there too: RSP is a
real, currently-trading Invesco ETF launched April 24, 2003, tracking the
S&P 500 Equal Weight Index. RSP's yfinance history begins within days
of that launch date (see the "RSP's real launch date" paragraph below
for the first usable bar).

Catalog mechanism (verbatim, ``data/mining/catalog.json``): "Hold the S&P
500 Equal-Weight Index -- each of the roughly 500 constituents held near
1/500th of the portfolio and mechanically rebalanced back to equal
weights every quarter -- instead of the market-cap-weighted S&P 500. This
forced quarterly rebalance systematically trims recent winners and adds
to recent losers back to par, harvesting a documented 'rebalancing
premium' plus an implicit tilt away from mega-cap concentration relative
to cap-weighting. The rule is simply to stay fully long the equal-weight
index continuously; any premium over SPY comes from the ETF's own
built-in rebalancing mechanism, not from a timing signal generated by
this pipeline."

RSP's real launch date is April 24, 2003 (catalog citation, verified via
stockanalysis.com/etfdb.com per the catalog entry). RSP's earliest
USABLE yfinance OHLC bar (yfinance is this family's price source) is
2003-05-01 -- a handful of trading days after the launch date, an
ordinary vendor-data-availability lag for a just-launched ETF, not a
discrepancy in the citation.

DISCLOSED SIMPLIFICATION / interpretation of PARAMETERS["rebalance"]
(following this pipeline's established honesty convention -- see e.g.
``spinoff_outperformance_effect.py``'s and ``free_cash_flow_yield_cows
.py``'s own disclosures of their limitations): ``PARAMETERS["rebalance"]
== "quarterly"`` describes RSP's OWN index methodology -- the quarterly
constituent-weight rebalance the S&P 500 Equal Weight Index's own
administrator already runs internally -- not a gating condition this
module needs to implement. RSP already IS the continuously-held,
already-rebalanced basket: the issuer/index runs the quarterly
rebalancing rule internally, on every share outstanding, with no action
required from a holder. There is therefore no per-bar decision left for a
signal function to make; the testable hypothesis reduces to "does
buy-and-hold RSP clear the mining pipeline's bars" (own-instrument alpha,
ABI-1 excess over SPY), not a market-timing or rebalance-triggered
question.

Catalog tickers note: the catalog's own "tickers" list is
``["RSP", "EQL", "SPY"]``. RSP (catalog tickers[0]) is the traded
instrument. EQL (catalog tickers[1]) is an alternate/redundant
equal-weight proxy, not an additional leg -- this module trades only
RSP and needs no SIGNAL tickers. SPY (catalog tickers[2]) is the catalog
entry's own "benchmark" parameter value, listed as a ticker only so a
benchmark-relative read could reference it directly; it is NOT read by
this module's signal_fn. Separately and coincidentally, ABI-1's BENCHMARK
constant below is also "SPY" -- that is ABI-1's own hard, unconditional
rule (every family is benchmarked against SPY, never a family's own
catalog "benchmark" field), not something this module derives from the
catalog field. The two "SPY"s agree here purely by coincidence, the same
disclosure every other batch5 single-proxy module in this pipeline makes
for this exact same shape.

Design (the four non-negotiable properties, all trivially satisfied by a
constant rule -- same as every other pure buy-and-hold batch5 candidate):

* NO LOOK-AHEAD -- the signal never reads a price at all (not even RSP's
  own), so there is nothing for a future bar to leak into a past decision.
* PERFORMANCE -- the returned closure returns a fixed SignalResult;
  nothing is computed per bar, let alone recomputed over a growing slice.
* HOLDOUT-BLIND -- likewise vacuous: with zero data dependency, truncating
  ``frames`` to <= the bucket's last bar cannot change anything the
  signal does.
* DIRECTION -- always long RSP, entered at the first structural
  opportunity and never exited by rule.

Interpretation choices (identical to ``spinoff_outperformance_effect.py``'s
own choices for the same always-long shape -- restated here rather than
imported, since each batch5 module is self-contained per this pipeline's
convention):

1. "Always long, never exited by rule" is implemented as entry=True /
   exit=False on EVERY bar the engine asks about, not just the first.
   ``backtest_engine.py``'s own docstring says the engine "only reads
   `entry` while flat and only reads `exit` while long", so a constant
   True entry is simply ignored once a position is open.
2. The engine enters at the EARLIEST bar it can structurally reach:
   ``run_backtest`` first asks about bar 0's decision while flat (the
   call ``signal_fn(df.iloc[:1], 0)`` made when evaluating bar 1), so
   that very first check already returns entry=True and the position
   opens at bar 1's open -- one bar of unavoidable engine latency common
   to every candidate in this pipeline, not a modeling choice made here.
3. No time stop, no signal exit, no cash state -- "buy-and-hold" is taken
   completely literally: the position is closed only by the engine's own
   end_of_data path (or an external time_stop the driver may separately
   impose), never by this module raising `exit`.
4. EXPECTED_MIN_TRADES = 1: with entry always True and exit always False,
   exactly one continuous holding period opens (at the bucket's first
   reachable bar) and is only ever closed by the engine's end_of_data path
   at the bucket's last bar -- so each bucket the driver runs this module
   over (in-sample, holdout, or ABI-1's full history) produces exactly one
   trade. This follows from the structure alone (a pure buy-and-hold
   rule cannot produce more than one trade per contiguous bucket); this
   module's own test checks it end to end on a synthetic fixture (exactly
   1 trade, held to end_of_data).
5. RSP's own frame is required to be present in `frames` (fail closed if
   missing, matching every other module's convention) even though its
   prices are never read by the signal -- this keeps the factory's
   contract identical to every other candidate's and gives a clear error
   if the driver's data plumbing ever fails to supply it, rather than
   silently trading blind.
"""
