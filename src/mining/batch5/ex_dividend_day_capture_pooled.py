def validate_events_payload(payload, *, where: str = "events payload") -> dict:
    """Fail-closed acceptance test for a loaded events.json.

    Refuses, rather than silently proceeding, when the file (a) is not this
    family's, (b) predates the fetcher's current guarantees, (c) does not
    carry a passing ``basis_check``, (d) carries a basis_check that read
    only ONE of the two split-basis directions, or (e) omits any ``TRADED``
    member. (d) is the schema-2 shape: a check that only looks for the
    conservative direction would otherwise pass as though it had cleared
    both.
    (e) matters because an absent member contributes no trades: a partial
    table would quietly shrink the pooled sample instead of failing.
    """
    if not isinstance(payload, dict) or payload.get("family_id") != FAMILY_ID:
        raise ValueError(f"{where}: not an events file for {FAMILY_ID}")
    version = payload.get("schema_version")
    if version != EXPECTED_SCHEMA_VERSION:
        raise ValueError(
            f"{where}: schema_version {version!r} != {EXPECTED_SCHEMA_VERSION} "
            "-- regenerate with scripts/fetch_batch5_events_"
            f"{FAMILY_ID}.py")
    basis = payload.get("basis_check")
    if not isinstance(basis, dict):
        raise ValueError(
            f"{where}: no 'basis_check' -- the file does not prove that the "
            "dividend amounts and the signal-bar closes share one split basis")
    if basis.get("status") != "verified" or basis.get("violations"):
        raise ValueError(
            f"{where}: basis_check did not pass (status="
            f"{basis.get('status')!r}, violations="
            f"{basis.get('violations')!r}); a split-adjustment race would "
            "silently mis-scale every yield for the member(s) named")
    directions = basis.get("directions")
    if not isinstance(directions, dict):
        raise ValueError(
            f"{where}: basis_check carries no 'directions' -- it cannot say "
            "which of the two split-basis races it looked for")
    unread = [name for name in REQUIRED_BASIS_DIRECTIONS
              if not isinstance(directions.get(name), dict)]
    if unread:
        raise ValueError(
            f"{where}: basis_check never read {unread} -- a check that looks "
            "only for the conservative direction (dividends adjusted, prices "
            "lagging) passes silently on the anti-conservative one (prices "
            "adjusted, amounts still pre-split), which OVERSTATES every "
            "pre-split yield by the split ratio")
    events = payload.get("events")
    if not isinstance(events, dict):
        raise ValueError(f"{where}: 'events' must be an object keyed by ticker")
    missing = [ticker for ticker in TRADED if ticker not in events]
    if missing:
        raise ValueError(
            f"{where}: {len(missing)} pool member(s) absent from the table "
            f"({missing[:5]}{'...' if len(missing) > 5 else ''}) -- an absent "
            "member produces no trades, silently shrinking the pooled sample")
    return events


@lru_cache(maxsize=1)
def _load_events_cached(path: str) -> dict:
    with open(path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)
    return validate_events_payload(payload, where=path)


def load_events() -> dict:
    """``{ticker: [record, ...]}`` from the family's events.json; each record
    carries ex_date, amount, signal_date, unadjusted_close_signal, yield,
    split_on_ex_date, prior_amount, trailing_median_amount and prior_count.
    The file is validated fail-closed first (``validate_events_payload``)."""
    return _load_events_cached(events_path())


# --------------------------------------------------------- event_counts sink
# Every exclusion this module makes -- below the yield floor, ex-date absent
# from the frame calendar, the two calendars disagreeing, a split-type
# adjustment factor on the ex-session, a secondary share class -- is counted
# in ``event_signal_dates`` and attached to the returned signal function as
# ``signal_fn.event_counts``. The driver never reads that attribute, so on
# its own none of it would reach the run output and no exclusion would be
# auditable from a report. The factory therefore also records every
# member's event_counts HERE, keyed
# by ticker, so the counts outlive the signal function and a caller can
# surface them after the run with one call. Keyed by ticker deliberately:
# the driver builds a fresh signal function per window (in-sample, holdout)
# from the SAME full-history frame, so both calls produce identical counts
# and last-write-wins cannot double-count.
EVENT_COUNTERS = (
    "events_total", "qualifying", "below_floor", "ex_date_not_in_calendar",
    "fewer_than_two_prior_sessions", "missing_yield_input",
    "signal_date_mismatch", "excluded_split_type_adjustment",
    "events_dropped_secondary_share_class",
)
_DIAGNOSTICS: dict = {}


def reset_diagnostics() -> None:
    """Empty the sink (a fresh run, or a test that wants isolation)."""
    _DIAGNOSTICS.clear()


def event_counts_by_ticker() -> dict:
    """``{ticker: event_counts}`` for every member the factory has built."""
    return {ticker: dict(counts) for ticker, counts in _DIAGNOSTICS.items()}


def pooled_diagnostics() -> dict:
    """Run-level roll-up of every per-member exclusion count.

    JSON-serializable and cheap, so a driver can attach it to its report
    item with one line, e.g. in ``run_batch5_mining.compute_candidate``::

        extra["event_diagnostics"] = getattr(module, "pooled_diagnostics", dict)()

    Shape::

        {"members": int,                     # members the factory ran for
         "totals": {counter: int, ...},      # EVENT_COUNTERS, summed
         "members_excluded_secondary_share_class": [ticker, ...],
         "members_with_qualifying_events": int}
    """
    totals = {name: 0 for name in EVENT_COUNTERS}
    secondary, with_events = [], 0
    for ticker, counts in _DIAGNOSTICS.items():
        for name in EVENT_COUNTERS:
            totals[name] += int(counts.get(name, 0) or 0)
        if counts.get("excluded_secondary_share_class"):
            secondary.append(ticker)
        if counts.get("qualifying"):
            with_events += 1
    return {"members": len(_DIAGNOSTICS), "totals": totals,
            "members_excluded_secondary_share_class": sorted(secondary),
            "members_with_qualifying_events": with_events}


def _clean_index(index) -> pd.DatetimeIndex:
    idx = pd.DatetimeIndex(pd.to_datetime(index))
    if idx.tz is not None:
        idx = idx.tz_localize(None)
    return idx.normalize()


def _finite_positive(value) -> bool:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return False
    return np.isfinite(number) and number > 0.0


def _is_cash_distribution(record) -> bool:
    """False when the ex-session also carries a split-type adjustment factor.

    yfinance encodes a spin-off / recapitalization / merger distribution as a
    dividend AND (often) as a same-session split, then applies both factors to
    the same corporate event when it auto-adjusts -- so the one-bar adjusted
    return on such a bar measures the double adjustment, not dividend capture,
    and the recorded "amount" is a share value fixed on or after E rather than
    a cash figure known at the E-2 signal bar. A missing field is treated as
    "no adjustment": the schema guarantees the field, and
    ``validate_events_payload`` refuses a file without that schema.

    The test fires on ANY non-unit factor, announced ratio or vendor-computed
    alike, and that is a deliberate choice with a disclosed cost: for a
    value-derived factor the number itself is dated E, so 11 of the 30 events
    this drops are removed using information the signal bar does not have.
    The direction is one-way (it can only remove events, and the removed ones
    are large positive adjustment artifacts) and the alternative inverts the
    hygiene -- see the module docstring, "Data hygiene", non-cash
    distributions, where both readings are measured.
    """
    factor = record.get("split_on_ex_date", 0.0)
    try:
        factor = float(factor)
    except (TypeError, ValueError):
        return False
    if not np.isfinite(factor):
        return False
    return factor in (0.0, 1.0)


def event_signal_dates(index, records, yield_floor: float):
    """Resolve one ticker's event records against its session calendar.

    Returns ``(entry_dates, exit_dates, event_counts)``: the set of E-2 signal
    dates, the set of matching ex-dates E, and counts of how each record was
    classified. Only the calendar (``index``) is consulted -- never a price
    in the frame -- so the result cannot depend on any bar's OHLC.

    Records whose ex-session also carries a split-type adjustment factor are
    dropped as non-cash distributions before any other test (see the module
    docstring, Data hygiene).
    """
    calendar = _clean_index(index)
    if not calendar.is_monotonic_increasing or calendar.has_duplicates:
        raise ValueError(f"{FAMILY_ID}: session calendar must be sorted and unique")
    position_of = {stamp.value: pos for pos, stamp in enumerate(calendar)}
    event_counts = {"events_total": 0, "qualifying": 0, "below_floor": 0,
                   "ex_date_not_in_calendar": 0,
                   "fewer_than_two_prior_sessions": 0,
                   "missing_yield_input": 0, "signal_date_mismatch": 0,
                   "excluded_split_type_adjustment": 0}
    entries, exits = set(), set()
    for record in records or ():
        event_counts["events_total"] += 1
        if not _is_cash_distribution(record):
            event_counts["excluded_split_type_adjustment"] += 1
            continue
        ex_date = pd.Timestamp(record["ex_date"]).normalize()
        pos = position_of.get(ex_date.value)
        if pos is None:
            event_counts["ex_date_not_in_calendar"] += 1
            continue
        signal_pos = pos - SIGNAL_SESSIONS_BEFORE_EX
        if signal_pos < 0:
            event_counts["fewer_than_two_prior_sessions"] += 1
            continue
        amount = record.get("amount")
        close = record.get("unadjusted_close_signal")
        if not (_finite_positive(amount) and _finite_positive(close)):
            event_counts["missing_yield_input"] += 1
            continue
        recorded_signal = record.get("signal_date")
        if (recorded_signal is None or
                pd.Timestamp(recorded_signal).normalize() != calendar[signal_pos]):
            event_counts["signal_date_mismatch"] += 1
            continue
        if float(amount) / float(close) < yield_floor:
            event_counts["below_floor"] += 1
            continue
        event_counts["qualifying"] += 1
        entries.add(calendar[signal_pos])
        exits.add(ex_date)
    return entries, exits, event_counts


def make_signal_fn(ticker: str, index: pd.DatetimeIndex, frames: dict, *,
                   events: dict | None = None):
    """Driver contract factory (event_pooled: called once per pool member with
    that member as ``ticker``). Resolves the member's ex-dividend events on
    its full-history frame calendar, maps the E-2 entry and E exit dates onto
    the bucket ``index`` as boolean arrays, and answers each engine call with
    O(1) lookups. ``events`` defaults to the family's events.json; tests pass
    a synthetic table.

    A member in ``SECONDARY_SHARE_CLASSES`` carries NO events, so it produces
    no trades and pools nothing -- that is how ``parameters.pool``'s "keep one
    share class per issuer" is honoured without editing ``TRADED`` or
    ``PARAMETERS``.

    Every member's exclusion counts are attached to the returned function as
    ``signal_fn.event_counts`` AND recorded in the module-level sink, so they
    survive the function and a run can surface them with one
    ``pooled_diagnostics()`` call (see that function)."""
    if ticker not in frames:
        raise ValueError(f"{FAMILY_ID}: no frame supplied for {ticker}")
    frame = frames[ticker]
    if not isinstance(frame, pd.DataFrame) or frame.empty or "Close" not in frame:
        raise ValueError(f"{FAMILY_ID}: {ticker} frame must be a non-empty "
                         "OHLC DataFrame with a Close column")
    calendar = _clean_index(frame.index)
    table = load_events() if events is None else events
    secondary = ticker in SECONDARY_SHARE_CLASSES
    records = () if secondary else table.get(ticker, [])
    entry_dates, exit_dates, event_counts = event_signal_dates(
        calendar, records, YIELD_FLOOR)
    event_counts["excluded_secondary_share_class"] = bool(secondary)
    event_counts["events_dropped_secondary_share_class"] = (
        len(table.get(ticker, [])) if secondary else 0)
    _DIAGNOSTICS[ticker] = dict(event_counts)

    bucket = _clean_index(index)
    if not bucket.is_monotonic_increasing or bucket.has_duplicates:
        raise ValueError(f"{FAMILY_ID}: bucket index must be sorted and unique")
    bucket_values = bucket.asi8
    entry_flags = np.fromiter((stamp in entry_dates for stamp in bucket),
                              dtype=bool, count=len(bucket))
    exit_flags = np.fromiter((stamp in exit_dates for stamp in bucket),
                             dtype=bool, count=len(bucket))

    def signal_fn(bar_frame: pd.DataFrame, i: int) -> SignalResult:
        if i < 0 or i >= len(bucket_values):
            raise ValueError(f"{FAMILY_ID}: bar position {i} outside the bucket")
        today = pd.Timestamp(bar_frame.index[-1])
        if today.tzinfo is not None:
            today = today.tz_localize(None)
        if today.normalize().value != bucket_values[i]:
            raise ValueError(
                f"{FAMILY_ID}: bar {today.date()} at position {i} does not match "
                f"the bucket calendar the factory was built for")
        return SignalResult(entry=bool(entry_flags[i]), exit=bool(exit_flags[i]))

    signal_fn.event_counts = dict(event_counts)
    signal_fn.ticker = ticker
    return signal_fn
