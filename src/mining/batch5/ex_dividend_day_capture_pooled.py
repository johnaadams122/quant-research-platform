# nothing and pools nothing. See the docstring, Interpretation choices.
SECONDARY_SHARE_CLASSES = ("GOOG", "FOX", "NWS")
# The events file this module will accept. Bumped when the fetcher's record
# schema or its guarantees change; an older file is refused, not tolerated.
# 3: the split-basis cross-check is two-directional (a schema-2 file reads
# only the conservative direction -- see "Data hygiene" in the docstring).
EXPECTED_SCHEMA_VERSION = 3
# Both readings the fetcher's basis_check must carry. A schema-3 file that
# names only one of them is refused: a one-directional check cannot be
# accepted as evidence for the direction it never looked at.
REQUIRED_BASIS_DIRECTIONS = ("price_history_unapplied", "dividend_series_unadjusted")

_REPO_ROOT = os.path.abspath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
_EVENTS_DIR = os.path.join("data", "mining", "batch5_events", FAMILY_ID)


